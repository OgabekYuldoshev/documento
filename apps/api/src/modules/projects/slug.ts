const MAX_LENGTH = 48;

export function slugify(name: string): string {
  const slug = name
    .toLowerCase()
    .replace(/['‘’ʻʼ`´]/g, "")
    .replace(/[а-яёўқғҳ]/g, (c) => CYRILLIC[c] ?? "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, MAX_LENGTH)
    .replace(/-+$/g, "");
  return slug || "project";
}
